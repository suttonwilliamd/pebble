type golden struct {
	Name         string   `json:"name"`
	Note         string   `json:"note"`
	Family       string   `json:"family"`
	WireHex      string   `json:"wire_hex"`
	ID           string   `json:"id"`
	Error        string   `json:"error"`
	Dependencies []string `json:"dependencies"`
	Offers       []string `json:"offers"`
}

func corpus(t *testing.T) (map[string]golden, []golden) {
	t.Helper()
	data, err := os.ReadFile("../formatcontract/testdata/v2.json")
	if err != nil {
		t.Fatal(err)
	}
	var c struct {
		Contract string   `json:"contract"`
		Vectors  []golden `json:"vectors"`
	}
	if err = json.Unmarshal(data, &c); err != nil {
		t.Fatal(err)
	}
	if c.Contract != "pebble-v2-pb01" {
		t.Fatal("unexpected contract")
	}
	byName := make(map[string]golden, len(c.Vectors))
	for _, v := range c.Vectors {
		if _, exists := byName[v.Name]; exists {
			t.Fatal("duplicate fixture", v.Name)
		}
		byName[v.Name] = v
	}
	return byName, c.Vectors
}
func goldenBytes(t *testing.T, v golden) []byte {
	t.Helper()
	b, err := hex.DecodeString(v.WireHex)
	if err != nil {
		t.Fatal(err)
	}
	return b
}
func goldenID(t *testing.T, v golden) ID {
	t.Helper()
	id, err := ParseID(v.ID)
	if err != nil {
		t.Fatal(v.Name, err)
	}
	return id
}
func newStore(t *testing.T) *Store {
	t.Helper()
	s, err := Init(context.Background(), t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	return s
}
func putGoldens(t *testing.T, s *Store, byName map[string]golden, names ...string) {
	t.Helper()
	seen := make(map[string]bool)
	var put func(string)
	put = func(name string) {
		if seen[name] {
			return
		}
		seen[name] = true
		v, ok := byName[name]
		if !ok || v.Error != "" || v.ID == "" {
			t.Fatal("not a valid object fixture", name)
		}
		for _, dependency := range v.Dependencies {
			put(dependency)
		}
		if err := s.Put(context.Background(), goldenID(t, v), bytes.NewReader(goldenBytes(t, v))); err != nil {
			t.Fatal(name, err)
		}
	}
	for _, name := range names {
		put(name)
	}
}
func assertRef(t *testing.T, s *Store, name string, want ID) {
	t.Helper()
	got, err := s.GetRef(context.Background(), name)
	if err != nil || got != want {
		t.Fatalf("%s: want %s, got %s (%v)", name, want, got, err)
	}
}
func assertAbsent(t *testing.T, path string) {
	t.Helper()
	if _, err := os.Lstat(path); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("expected absent %s, got %v", path, err)
	}
}

// This is the frozen PB-01 corpus, not a copy regenerated by this implementation.
// Every record is exercised: markers by Open, six object kinds by Put/Verify,
// and protocol messages by rejection from the addressable object boundary.
func TestProductionGoldenConformance(t *testing.T) {
	byName, vectors := corpus(t)
	ctx := context.Background()
	for _, v := range vectors {
		t.Run(v.Name, func(t *testing.T) {
			s := newStore(t)
			wire := goldenBytes(t, v)
			if v.Family == "marker" {
				if err := os.WriteFile(filepath.Join(s.meta, "format"), wire, 0600); err != nil {
					t.Fatal(err)
				}
				_, err := Open(s.root)
				if (err != nil) != (v.Error != "") {
					t.Fatalf("marker acceptance: %v", err)
				}
				return
			}
			if len(wire) >= HeaderSize && wire[4] >= 0x80 {
				if err := s.Put(ctx, goldenID(t, byName["chunk-a"]), bytes.NewReader(wire)); err == nil {
					t.Fatal("protocol record stored as object")
				}
				assertAbsent(t, s.objectPath(goldenID(t, byName["chunk-a"])))
				return
			}
			putGoldens(t, s, byName, v.Dependencies...)
			id := goldenID(t, byName["chunk-a"])
			if v.ID != "" {
				var err error
				id, err = ParseID(v.ID)
				if err != nil {
					if v.Error == "" {
						t.Fatal(err)
					}
					return
				}
			}
			err := s.Put(ctx, id, bytes.NewReader(wire))
			if err == nil {
				err = s.Verify(ctx, id)
			}
			if v.Error != "" {
				if err == nil {
					t.Fatal("invalid object/graph accepted:", v.Note)
				}
				if _, statErr := os.Lstat(s.objectPath(id)); statErr == nil {
					if updateErr := s.UpdateRef(ctx, "tags/probe", nil, id); updateErr == nil {
						t.Fatal("invalid graph published")
					}
					assertAbsent(t, s.refPath("tags/probe"))
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			computed, err := NewID(id.Kind, wire[HeaderSize:])
			if err != nil || computed != id {
				t.Fatalf("canonical address differs from pinned golden: %s %v", computed, err)
			}
			var restored bytes.Buffer
			if err = s.Copy(ctx, id, &restored); err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(restored.Bytes(), wire) {
				t.Fatal("stored bytes differ from canonical envelope")
			}
		})
	}
}

func TestEqualPayloadsRemainDistinctTypes(t *testing.T) {
	byName, _ := corpus(t)
	s := newStore(t)
	putGoldens(t, s, byName, "tree-empty", "chunk-tree-payload")
	tree, chunk := goldenID(t, byName["tree-empty"]), goldenID(t, byName["chunk-tree-payload"])
	if tree == chunk || tree.Digest == chunk.Digest {
		t.Fatal("kind was not included in native address")
	}
	for _, id := range []ID{tree, chunk} {
		var wire bytes.Buffer
		if err := s.Copy(context.Background(), id, &wire); err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(wire.Bytes()[HeaderSize:], []byte{0, 0, 0, 0}) || Kind(wire.Bytes()[4]) != id.Kind {
			t.Fatal("object kind/content collision")
		}
	}
}
